/** The catalog text for a list of parsed blocks. */
export function buildCatalog(blocks) {
  const out = [HEAD];
  for (const b of blocks) {
    out.push(`\n**${b.name}** ${b.pick || clip(b.summary, 120)}\n\`${b.example}\`${b.note ? '\n' + b.note : ''}`);
  }
  return out.join('') + '\n\n' + MOTION;
}

const main = () => {
  const text = buildCatalog(readBlocks());
  const size = Buffer.byteLength(text);
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch (_) { /* missing */ }
    if (cur !== text) { process.stderr.write('BLOCKS.md is out of date: run node addon/kit/blocks/gen-catalog.mjs\n'); process.exit(1); }
    process.stdout.write(`BLOCKS.md up to date (${size} bytes)\n`);
    return;
  }
  writeFileSync(OUT, text);
  process.stdout.write(`wrote ${OUT} (${size} bytes${size > MAX_BYTES ? `, OVER the ${MAX_BYTES} byte target` : ''})\n`);
  if (size > MAX_BYTES) process.exitCode = 1;
};
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
