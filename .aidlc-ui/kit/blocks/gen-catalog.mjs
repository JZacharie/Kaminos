#!/usr/bin/env node
// node addon/kit/blocks/gen-catalog.mjs [--check]
// Writes addon/kit/BLOCKS.md (the catalog builder agents read) from the `/* @block ... */` doc comment at the top of every kit/blocks/<name>.js.
// The doc comments are the source: to change a catalog line, edit the block's header (`Pick:` = when to choose it, `Call:` = the minimal config), then run this again.
// --check exits 1 when BLOCKS.md differs from what this would write. Node 22, no dependencies.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = join(HERE, '..', 'BLOCKS.md');
export const MAX_BYTES = 12 * 1024;   // was 6 KB for 15 blocks; 23 blocks (8 consumer-style ones added by BK1, 2026-11-17) need about 8 KB; 9 KB since tracks and inspector (KC1, 2026-11-20: 25 blocks incl. tracks and inspector)

/** The header comment of a block file, or '' when it has none. */
const header = (text) => {
  const m = /^\/\*[\s\S]*?\*\//.exec(text);
  return m && /^\/\*\s*@block\s/.test(m[0]) ? m[0] : '';
};
/** Lines of one `Key:` field of the doc comment (the first line plus indented continuation lines), joined by a space. */
const field = (doc, key) => {
  const lines = doc.split('\n');
  const i = lines.findIndex((l) => new RegExp('^ \\* ' + key + ':').test(l));
  if (i < 0) return '';
  const out = [lines[i].replace(new RegExp('^ \\* ' + key + ':\\s*'), '')];
  for (let j = i + 1; j < lines.length && /^ \*\s{2,}\S/.test(lines[j]); j++) out.push(lines[j].replace(/^ \*\s+/, ''));
  return out.join(' ').trim();
};
/** The text of the second argument of K.block.<name>(sel, {...}): balanced braces, strings respected. */
const configArg = (call) => {
  const i = call.indexOf('{', call.indexOf(','));
  if (i < 0) return '';
  let depth = 0, q = '';
  for (let k = i; k < call.length; k++) {
    const c = call[k];
    if (q) { if (c === '\\') k++; else if (c === q) q = ''; continue; }
    if (c === "'" || c === '"' || c === '`') q = c;
    else if (c === '{' || c === '[' || c === '(') depth++;
    else if (c === '}' || c === ']' || c === ')') { depth--; if (depth === 0) return call.slice(i, k + 1); }
  }
  return '';
};
/** Whitespace out except inside strings and between two identifier characters. */
const compact = (src) => {
  let out = '', q = '', pend = false;
  for (let k = 0; k < src.length; k++) {
    const c = src[k];
    if (q) { out += c; if (c === '\\') out += src[++k]; else if (c === q) q = ''; continue; }
    if (/\s/.test(c)) { pend = true; continue; }
    if (pend && /[\w$'"]/.test(out.slice(-1)) && /[\w$'"]/.test(c)) out += ' ';
    pend = false;
    if (c === "'" || c === '"' || c === '`') q = c;
    out += c;
  }
  return out;
};
const clip = (s, n) => {
  s = s.replace(/\s+/g, ' ').trim();
  if (s.length <= n) return s;
  const cut = s.slice(0, n);
  const at = Math.max(cut.lastIndexOf(', '), cut.lastIndexOf('; '), cut.lastIndexOf(' ('));
  return (at > n * 0.5 ? cut.slice(0, at) : cut.slice(0, cut.lastIndexOf(' '))).replace(/[,;:(\s]+$/, '') + ' ...';
};

/** Parse one block file: {name, version, summary, pick, example, note?}. `Note:` is one optional extra catalog line (KL1: the brand.icon names of the shell). */
export function parseBlock(text, file = '') {
  const doc = header(text);
  const m = /^\/\*\s*@block\s+([a-z][a-z0-9]*)\s+(\S+)\s*--\s*([^\n]*)/.exec(doc);
  if (!m) return null;
  const summary = m[3].replace(/\s*\*\/\s*$/, '');
  const pick = field(doc, 'Pick');
  const call = field(doc, 'Call');
  return { name: m[1], version: m[2], summary, pick, example: compact(configArg(call)), note: field(doc, 'Note'), file };
}

/** All blocks of a directory, sorted by name. */
export function readBlocks(dir = HERE) {
  return readdirSync(dir).filter((f) => /^[a-z][a-z0-9]*\.js$/.test(f) && f !== 'core.js').sort()
    .map((f) => parseBlock(readFileSync(join(dir, f), 'utf8'), f)).filter(Boolean);
}

const HEAD = `# UI blocks catalog (generated by kit/blocks/gen-catalog.mjs; do not edit)
Compose every screen from these blocks first; hand-write HTML only for what no block covers (fallback: kit/components). Never hand-draw a table, chart, map, plan, timeline, KPI row or nav that a block covers.
Load: list the names in head.json \`"blocks":[...]\` or do nothing: ui-build also finds \`data-k-block\` and \`K.block.<name>(\`. Themes: \`K.theme.set('ops'|'control'|'warm')\`.
Declarative: \`<div id="a-ship" data-k-block="table" data-k-cfg="ship"></div>\` in the screen, and in src/screens/NN-<id>.blocks.js \`UI_BLOCKS.ship = function (CANON, el) { var D = window.APP_DATA; return {...}; }\` with the config below. Imperative: \`K.block.table('#a-ship', cfg)\`.
Every block also takes \`title, subtitle, actions, state ('loading'|'empty'|'error'), emptyText, frame, headingLevel (default 2 = under the screen h1; 3 inside a section with its own h2), colorKeys\`. Categories: \`K.block.palette({'Stage A':0,...})\` once per page keeps a key's colour equal on every screen. Accent: head.json \`accent\` (blue, green, teal, gold, indigo, violet, rose, orange). Blocks print the numbers they are given (pass totals; they never sum). Time fields take 'HH:MM', an ISO date-time or a JS Date (14:30 today, else 12 Nov, 14:30). A wrong optional field shows an em dash and warns once; text with undefined, NaN or null is flagged (data-k-suspect), fix the data. Put the \`a-...\` anchor id on the placeholder. Cards side by side in one \`k-grid\` row: a short card next to a tall one stays short; add class \`k-row-fill\` to the grid (or \`fill:true\` on a card) and the blocks whose Config lists \`fill\` (feed, detail, table...) use the row height (more rows or roomier rows, never a taller row); \`fill:'scroll'\` scrolls the card inside instead. Every field of a block: the \`Config:\` comment at the top of kit/blocks/<name>.js.
`;

// Motion (KN1, 2026-11-23): not a block, so it has no @block header; this paragraph is its entry in the catalog (full list: kit/README.md "Motion"). +1.7 KB, so the cap went from 9 to 11 KB.
